#!/usr/bin/env python3
"""
LaTeX tables for the SI - V3 data only - generated from the analysis CSVs so the numbers cannot drift.

  ~/software/miniforge3/envs/qtaim/bin/python local_analysis/make_latex_tables.py

Writes ../article/<rev>/tables/*.tex (QTAIM_REV, see qtaim_local.py) (tabular bodies only; environments and captions live in article/si.tex):
  tabS_md.tex       per V3 system: replicas, C3'-endo fractions (RNA strand, residue 6, DNA strand),
                    fraction of frames with the central pair / neighbour pairs open
  tabS_frames.tex   QTAIM frames per system: planned, QC-passing, paired (once V3 QTAIM exists)
  tabS_rhofits.tex  rho = a exp(-b d) fits (once V3 QTAIM exists)
A table whose input is not available yet is written as a one-line placeholder.
"""
from pathlib import Path

import pandas as pd

import qtaim_local as ql
from qtaim_local import cs

HERE = Path(__file__).resolve().parent
TAB, MDTAB = ql.TAB, ql.MDTAB          # QTAIM-derived tables of QTAIM_REV; MD-only tables (shared)
OUT = ql.ARTICLE / "tables"            # article/<rev>/tables
OUT.mkdir(exist_ok=True)
LABEL = {v[0]: v[1] for v in cs.SYSTEMS.values()}
RULES = ("\\midrule", "\\toprule", "\\bottomrule")


def lab(sysd):
    if sysd.startswith("control"):
        return "control"
    return LABEL.get(sysd, LABEL.get(sysd.replace("_std/", "_v3/"), LABEL.get(sysd + "_rst", sysd))).replace("'", "$^\\prime$")


def tt(x):
    return "\\texttt{" + x.replace("_", "\\_") + "}"


def write(name, header, rows, colspec):
    body = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    body += [r if r.startswith(RULES) else r + " \\\\" for r in rows]
    body += ["\\bottomrule", "\\end{tabular}"]
    (OUT / name).write_text("% generated by local_analysis/make_latex_tables.py - do not edit by hand\n" + "\n".join(body) + "\n")


def placeholder(name, text):
    (OUT / name).write_text("% generated by local_analysis/make_latex_tables.py - do not edit by hand\n"
                            f"\\textcolor{{blue}}{{[pending: {text}]}}\n")


def md():
    d, s = pd.read_csv(MDTAB / "md_pucker_strands.csv"), pd.read_csv(MDTAB / "md_structure_summary.csv")
    rows = []
    for ctx, head in (("U", "U context"), ("A", "A context"), ("GC", "G:C context")):
        dd = d[d.context == ctx]
        if dd.empty:
            continue
        rows.append(f"\\multicolumn{{7}}{{l}}{{\\textit{{{head}}}}}")
        for sysd, g in dd.groupby("system", sort=True):
            per = g.groupby("replica")
            rna = per.apply(lambda x: x[(x.strand == "RNA") & (x.resid != 6)].frac_north.mean()).mean()
            r6 = per.apply(lambda x: x[x.resid == 6].frac_north.mean()).mean()
            dna = per.apply(lambda x: x[x.strand == "DNA"].frac_north.mean()).mean()
            o = s[s.system == sysd]
            rows.append(f"{lab(sysd)} & {g.replica.nunique()} & {rna:.2f} & "
                        f"{r6:.2f} & {dna:.2f} & {o.imino_6_frac_open.mean():.3f} & "
                        f"{max(o.imino_5_frac_open.mean(), o.imino_7_frac_open.mean()):.3f}")
    write("tabS_md.tex", "System & Replicas & RNA & Res.~6 & DNA & Pair 6 open & Pair 5/7 open",
          rows, "lrrrrrr")


def frames():
    f = TAB / "frame_status.csv"
    if not f.exists():
        placeholder("tabS_frames.tex", "QTAIM frame statistics of the V3 data set")
        return
    st = pd.read_csv(f)
    st = st[st.frames_finished > 0]
    if st.empty:
        placeholder("tabS_frames.tex", "QTAIM frame statistics of the V3 data set")
        return
    # one row per modification, the three contexts side by side (U, A, G:C; user 2026-10-14);
    # set3/sys01 is Sp-PS + 2'-F in the A context and Rp-PS + 2'-F in the G:C context: one row
    st = st.assign(row=st.system.replace({"Rp-PS+2'-F": "Sp-PS+2'-F"}))
    ctxs = [c for c in ("U_v3", "A_v3", "GC_v3") if c in set(st.context)]
    order = list(dict.fromkeys(st[st.context == "A_v3"].row)) + [r for r in dict.fromkeys(st.row)
                                                                if r not in set(st[st.context == "A_v3"].row)]
    rows = []
    for r in order:
        lab_ = {"Sp-PS+2'-F": "PS+2'-F$^{\\ddagger}$"}.get(r, r).replace("'", "$^\\prime$").replace("+", " + ")
        cells = []
        for c in ctxs:
            g = st[(st.context == c) & (st.row == r)]
            cells += (["--"] * 4 if g.empty else
                      [str(g.frames_finished.sum()), str(g.frames_used.sum()), str(g.frames_paired.sum()),
                       str(g.frames_with_NNA.sum())])
        rows.append(f"{lab_} & " + " & ".join(cells))
    head = {"U_v3": "U context", "A_v3": "A context", "GC_v3": "G:C context"}
    top = " & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{head[c]}}}" for c in ctxs) + " \\\\\n" + \
          "".join(f"\\cmidrule(lr){{{2 + 4 * k}-{5 + 4 * k}}}" for k in range(len(ctxs))) + "\n"
    write("tabS_frames.tex", top + "System" + " & Fin. & QC & Paired & NNA" * len(ctxs), rows,
          "l" + "rrrr" * len(ctxs))


def rhofits():
    f = TAB / "rho_distance_fits.csv"
    if not f.exists():
        placeholder("tabS_rhofits.tex", "fits of the V3 data set")
        return
    d = pd.read_csv(f)
    rows = [f"{r.hbond.replace('···', '$\\cdots$')} & {r.n} & {r.a:.2f} & {r.b:.2f} & {r.R2:.3f} & "
            f"{r.d_min:.2f}--{r.d_max:.2f}" for r in d.itertuples()]
    write("tabS_rhofits.tex", "H-bond type & $n$ & $a$ / a.u. & $b$ / \\AA$^{-1}$ & $R^2$ & $d$ range / \\AA", rows,
          "lrrrrl")


def nastruct():
    fb, fs = MDTAB / "nastruct_bp.csv", MDTAB / "nastruct_step.csv"
    if not fb.exists():
        placeholder("tabS_nastruct.tex", "helical parameters of the V3 data set")
        return
    b, s = pd.read_csv(fb), pd.read_csv(fs)
    ctrl = {"A": "control02_v3", "GC": "control03_v3", "U": "control01_v3_rst"}
    rows = []
    for ctx, head in (("U", "U context (U6:dA17)"), ("A", "A context (A6:dT17)"), ("GC", "G:C context (G6:dC15)")):
        bb, ss = b[b.context == ctx], s[s.context == ctx]
        if bb.empty:
            continue
        rows.append(f"\\multicolumn{{10}}{{l}}{{\\textit{{{head}}}}}")

        def val(sysd):
            p6 = bb[(bb.system == sysd) & (bb.pair == 6)]
            s56, s67 = ss[(ss.system == sysd) & (ss.step_i == 5)], ss[(ss.system == sysd) & (ss.step_i == 6)]
            return [p6.propeller_mean.mean(), p6.opening_mean.mean(), p6.buckle_mean.mean(),
                    s56.roll_mean.mean(), s56.twist_mean.mean(), s67.roll_mean.mean(), s67.twist_mean.mean(),
                    pd.concat([s56, s67]).minor_mean.mean()]
        c = val(ctrl[ctx]) if ctrl[ctx] in set(bb.system) else None
        for sysd in sorted(set(bb.system)):
            v = val(sysd)
            if c is not None and sysd != ctrl[ctx]:
                cells = [f"{x:.1f} ({x - y:+.1f})" for x, y in zip(v, c)]
            else:
                cells = [f"{x:.1f}" for x in v]
            rows.append(f"{lab(sysd)} & {bb[bb.system == sysd].replica.nunique()} & " + " & ".join(cells))
    write("tabS_nastruct.tex", "System & Rep. & Prop.~6 & Open.~6 & Buckle~6 & Roll 5--6 & Twist 5--6 & Roll 6--7 & "
          "Twist 6--7 & Minor groove", rows, "lrrrrrrrrr")


if __name__ == "__main__":
    md(); frames(); rhofits(); nastruct()
    print("[OK]", sorted(p.name for p in OUT.glob("tabS_*.tex")))
